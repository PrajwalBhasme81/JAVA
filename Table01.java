public class Table01
{
    public static void Weight() 
	{
        int weightOfTable = 90;
        if (weightOfTable > 80) {
            System.out.println("Weight Of the Table is greater than 80 Kg");
        }
        if (weightOfTable < 100) {
            System.out.println("Weight Of the Table is less than 100 Kg");
        }
        if (weightOfTable == 90) {
            System.out.println("Weight Of the Table is equal to 90 Kg");
        }
        if (weightOfTable != 85) {
            System.out.println("Weight Of the Table is not equal to 85 Kg");
        }
        if (weightOfTable >= 90) {
            System.out.println("Weight Of the Table is greater than or equal to 90 Kg");
        }
    }

    public static void Types() 
	{
        int typesOfTables = 6;
        if (typesOfTables > 5) {
            System.out.println("Types of Tables is greater than 5");
        }
        if (typesOfTables < 10) {
            System.out.println("Types of Tables is less than 10");
        }
        if (typesOfTables == 6) {
            System.out.println("Types of Tables is equal to 6");
        }
        if (typesOfTables != 8) {
            System.out.println("Types of Tables is not equal to 8");
        }
        if (typesOfTables >= 6) {
            System.out.println("Types of Tables is greater than or equal to 6");
        }
    }

    public static void Collections() 
	{
        int collections = 110;
        if (collections > 105) {
            System.out.println("Number Of Collections are greater than 105");
        }
        if (collections < 115) {
            System.out.println("Number Of Collections are less than 115");
        }
        if (collections == 110) {
            System.out.println("Number Of Collections are equal to 110");
        }
        if (collections != 108) {
            System.out.println("Number Of Collections are not equal to 108");
        }
        if (collections >= 110) {
            System.out.println("Number Of Collections are greater than or equal to 110");
        }
    }
}
